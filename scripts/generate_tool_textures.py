def make_block_texture(base_color, border_color):
    img = Image.new("RGBA", (16, 16), hex_to_rgb(base_color) + (255,))
    border_rgb = hex_to_rgb(border_color) + (255,)
    for i in range(16):
        img.putpixel((i, 0), border_rgb)
        img.putpixel((i, 15), border_rgb)
        img.putpixel((0, i), border_rgb)
        img.putpixel((15, i), border_rgb)
    return img

