def hex_to_rgb(hex_val):
    if isinstance(hex_val, str):
        hex_val = int(hex_val.replace('#', '').replace('0x', ''), 16)
    r = (hex_val >> 16) & 0xFF
    g = (hex_val >> 8) & 0xFF
    b = hex_val & 0xFF
    return (r, g, b)

def clamp(v):
    return max(0, min(255, int(v)))

def get_tinted_palette(hex_val):
    r, g, b = hex_to_rgb(hex_val)
    return {
        '.': (0, 0, 0, 0),
        '1': (clamp(r * 1.35 + 25), clamp(g * 1.35 + 25), clamp(b * 1.35 + 25), 255),
        '2': (clamp(r * 1.15 + 10), clamp(g * 1.15 + 10), clamp(b * 1.15 + 10), 255),
        '3': (r, g, b, 255),
        '4': (clamp(r * 0.68), clamp(g * 0.68), clamp(b * 0.68), 255),
        '5': (clamp(r * 0.40), clamp(g * 0.40), clamp(b * 0.40), 255),
        '6': (clamp(r * 0.22), clamp(g * 0.22), clamp(b * 0.22), 255),
    }

