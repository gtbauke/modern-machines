def render_ascii_to_image(ascii_art, palette):
    lines = [l for l in ascii_art.strip().splitlines()]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(min(len(lines), 16)):
        line = lines[y]
        for x in range(min(len(line), 16)):
            char = line[x]
            if char in palette:
                img.putpixel((x, y), palette[char])
    return img

def composite_on_background(bg_img, overlay_img):
    result = bg_img.copy()
    result.paste(overlay_img, (0, 0), overlay_img)
    return result

